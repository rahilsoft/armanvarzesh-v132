import { themes, Theme } from './themes';
import { fontFamilies, fontSizes, fontWeights, lineHeights, space, radius, elevation, motion, zIndex, breakpoints } from './scales';

const kebab = (s: string) => s.replace(/([A-Z])/g, '-$1').toLowerCase();

export function themeVariables(theme: Theme): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(theme)) out[`--av-color-${kebab(k)}`] = v;
  return out;
}

export function staticVariables(): Record<string, string> {
  const out: Record<string, string> = {
    '--av-font-family': fontFamilies.web,
    '--av-font-mono': fontFamilies.mono,
  };
  for (const [k, v] of Object.entries(fontSizes)) out[`--av-font-size-${k}`] = `${v}px`;
  for (const [k, v] of Object.entries(fontWeights)) out[`--av-font-weight-${k}`] = String(v);
  for (const [k, v] of Object.entries(lineHeights)) out[`--av-line-height-${k}`] = String(v);
  for (const [k, v] of Object.entries(space)) out[`--av-space-${k}`] = `${v}px`;
  for (const [k, v] of Object.entries(radius)) out[`--av-radius-${k}`] = `${v}px`;
  for (const [k, v] of Object.entries(elevation)) out[`--av-shadow-${k}`] = v.css;
  for (const [k, v] of Object.entries(motion.duration)) out[`--av-duration-${k}`] = `${v}ms`;
  for (const [k, v] of Object.entries(motion.easing)) out[`--av-easing-${k}`] = v;
  for (const [k, v] of Object.entries(zIndex)) out[`--av-z-${k}`] = String(v);
  for (const [k, v] of Object.entries(breakpoints)) out[`--av-breakpoint-${k}`] = `${v}px`;
  return out;
}

function block(selector: string, vars: Record<string, string>, extra = '', indent = ''): string {
  const body = Object.entries(vars).map(([k, v]) => `${indent}  ${k}: ${v};`).join('\n');
  return `${indent}${selector} {\n${extra ? indent + extra : ''}${body}\n${indent}}\n`;
}

/** Full stylesheet: dark is default; light via [data-theme='light'] or prefers-color-scheme. */
export function generateCss(): string {
  const dark = themeVariables(themes.dark);
  const light = themeVariables(themes.light);
  return [
    '/* Generated by @arman/ui-tokens (scripts/generate-css.cjs). Do not edit. */',
    block(':root', { ...staticVariables(), ...dark }, '  color-scheme: dark;\n'),
    block(":root[data-theme='dark']", dark, '  color-scheme: dark;\n'),
    block(":root[data-theme='light']", light, '  color-scheme: light;\n'),
    `@media (prefers-color-scheme: light) {\n${block(":root:not([data-theme='dark'])", light, '  color-scheme: light;\n', '  ')}}\n`,
    ":root { direction: rtl; }\n",
  ].join('\n');
}
